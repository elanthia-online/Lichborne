// Writes src/renderer/components/panels/damaps/forageItems.ts: the names of
// everything that can be foraged, from dr-scripts' data/base-forage.yaml (the
// list its forage script uses). Da'Maps shows a Lich room tag as forage only
// when it names one of these, so NPCs, shops and room nicknames stay out.
//
//   node tools/damaps/build-forage-items.mjs <path to dr-scripts>/data/base-forage.yaml
import { readFileSync, writeFileSync } from 'node:fs'
const src = process.argv[2]
if (!src) { console.error('usage: build-forage-items.mjs <base-forage.yaml>'); process.exit(1) }
const items = [...new Set(readFileSync(src, 'utf8').split(/\r?\n/)
  .map(l => /^- item:\s*(.+?)\s*$/.exec(l)?.[1]).filter(Boolean)
  .map(s => s.replace(/^['"]|['"]$/g, '').toLowerCase()))].sort()
const out = `// GENERATED by tools/damaps/build-forage-items.mjs from dr-scripts'
// data/base-forage.yaml (${items.length} items). Re-run it to update.
export const FORAGE_ITEMS: readonly string[] = ${JSON.stringify(items, null, 2)}
`
writeFileSync(new URL('../../src/renderer/components/panels/damaps/forageItems.ts', import.meta.url), out)
console.log(`${items.length} forage items`)
