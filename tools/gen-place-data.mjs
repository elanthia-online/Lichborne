// gen-place-data — snapshot which TOWN each room-title prefix belongs to, from
// Lich's map database, into a committed TypeScript table (v0.20.3).
//
//   node tools/gen-place-data.mjs <path to map-NNNN.json>
//
// The Living Tableau draws a town in its own style (Shard's crystal spires,
// Muspar'i's sandstone domes). A room title usually starts with the place
// ("[Ratha, Amakra Close]"), but districts and buildings often don't name the
// town ("[Undershard, …]", "[Crossing Temple, …]", "[Theren Keep, …]"). The
// map's `location` field does, so this maps every title prefix whose rooms
// mostly sit in one town to that town. Committed rather than read at runtime
// because the Tableau must work without Lich (Principle #2), and the map DB is
// 15 MB. Re-run when Lich's map grows. Rooms the table can't place fall back to
// the last town the character was in (tableauPlaces.ts).
import fs from 'node:fs'

// location (from the map) → place key. First match wins; order matters only
// where two patterns could both match.
const LOCATIONS = [
  [/^lost crossing/i, null],
  [/^(the )?crossing\b/i, 'crossing'],
  [/^riverhaven($| market)|^haven west gate/i, 'riverhaven'],
  [/^(therenborough|theren keep)/i, 'therenborough'],
  [/^ratha\b/i, 'ratha'],
  [/^aesry\b/i, 'aesry'],
  [/^(shard|undershard|the great tower)\b/i, 'shard'],
  [/^mer'?kresh/i, 'merkresh'],
  [/^muspar'i/i, 'muspari'],
  [/^(inner |outer )?hibarnhvidar/i, 'hibarnhvidar'],
  [/^leth deriel/i, 'leth'],
  [/^throne city/i, 'throne'],
  [/^dirge\b/i, 'dirge'],
  [/^langenfirth$/i, 'langenfirth'],
  [/^siksraja/i, 'siksraja'],
  [/^(rossman's landing|rossgallan keep)/i, 'rossman'],
  [/^ilaya taipa/i, 'ilaya'],
  [/^acenamacra/i, 'acenamacra'],
  [/^boar clan/i, 'boarclan'],
  [/^tiger clan/i, 'tigerclan'],
  [/^knife clan/i, 'knifeclan'],
  [/^steelclaw clan/i, 'steelclaw'],
  [/^horse clan/i, 'zaldi'],
  [/sunfall hub/i, 'sunfall'],
  [/^ain ghazal/i, 'ainghazal'],
  [/^dragonspine fortress/i, 'chyolvea'],
  [/^fornsted/i, 'fornsted'],
  [/^raven's point/i, 'ravenspoint'],
  [/^stone clan/i, 'stoneclan'],
  [/^arthelun/i, 'arthelun'],
]

const file = process.argv[2]
if (!file) { console.error('usage: node tools/gen-place-data.mjs <map.json>'); process.exit(1) }
const db = JSON.parse(fs.readFileSync(file, 'utf8'))
const placeOfLoc = loc => { for (const [re, k] of LOCATIONS) if (re.test(loc)) return k; return undefined }
const prefixOf = title => {
  const t = title.replace(/^\[+|\]+$/g, '').trim()
  return (t.includes(',') ? t.slice(0, t.indexOf(',')) : t).trim().toLowerCase()
}

const tally = new Map()  // prefix → { total, places: Map<key|null, n> }
for (const r of db) {
  if (!r.title?.length) continue
  const p = prefixOf(r.title[0])
  if (!p) continue
  let e = tally.get(p); if (!e) tally.set(p, e = { total: 0, places: new Map() })
  e.total++
  const k = placeOfLoc(r.location ?? '')
  if (k !== undefined) e.places.set(k, (e.places.get(k) ?? 0) + 1)
}

const out = []
let rooms = 0
for (const [p, e] of tally) {
  const best = [...e.places].sort((a, b) => b[1] - a[1])[0]
  // At least two rooms placed, and most of the prefix's rooms in that one town.
  if (!best || !best[0] || best[1] < 2 || best[1] < e.total * 0.6) continue
  out.push([p, best[0]]); rooms += e.total
}
out.sort((a, b) => a[0].localeCompare(b[0]))

const body = out.map(([p, k]) => `  ${JSON.stringify(p)}: '${k}',`).join('\n')
const src = `// GENERATED by tools/gen-place-data.mjs from Lich's map database — do not edit.
// Room-title prefix (lowercased, before the first comma) → the town it is in.
// ${out.length} prefixes covering ${rooms} rooms. Re-run the generator when the map grows.
import type { PlaceKey } from './tableauPlaces'

export const PLACE_PREFIXES: Record<string, PlaceKey> = {
${body}
}
`
fs.writeFileSync(new URL('../src/renderer/components/experiences/placeData.ts', import.meta.url), src)
console.log(`wrote ${out.length} prefixes covering ${rooms} rooms`)
